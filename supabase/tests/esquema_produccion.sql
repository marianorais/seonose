-- --- Stubs de Supabase -------------------------------------------------------
create role anon nologin;
create role authenticated nologin;

create schema auth;
grant usage on schema auth to anon, authenticated;

-- Igual que en Supabase: el usuario sale del claim `sub` del JWT de la request.
create function auth.uid() returns uuid
language sql stable
as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;

create table auth.users (id uuid primary key);

grant usage on schema public to anon, authenticated;

-- --- Tablas -------------------------------------------------------------------
create table public.categories (
  id bigint primary key,
  name varchar not null unique,
  createdat timestamptz default now(),
  icon text
);

create table public.questions (
  id bigint generated by default as identity primary key,
  question text not null default '',
  answer text not null,
  choices jsonb,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  availablefrom date default (current_date + interval '1 day'),
  repeatable boolean not null default false,
  categoryid bigint references public.categories(id)
);

create table public.daily_quiz (
  id bigint generated by default as identity primary key,
  date date not null,
  questionid bigint not null references public.questions(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint daily_quiz_date_questionid_key unique (date, questionid)
);
create index daily_quiz_date_idx on public.daily_quiz (date);

create table public.game_sessions (
  id bigint generated by default as identity primary key,
  startedat timestamptz not null,
  completedat timestamptz,
  totalquestions integer not null,
  correctanswers integer not null default 0,
  shareurl text,
  userip text,
  useragent text,
  playerid text
);
create index game_sessions_playerid_idx on public.game_sessions (playerid);

create table public.game_answers (
  id bigint generated by default as identity primary key,
  gamesessionid bigint not null references public.game_sessions(id),
  questionid bigint not null references public.questions(id),
  selectedanswer text not null,
  correctanswer text not null,
  iscorrect boolean not null,
  responsetime integer not null
);

create table public.game_sessions_backup_unificacion as
select id, playerid, userip, completedat from public.game_sessions;

create table public.game_settings (
  id bigint generated by default as identity primary key,
  secondsperquestion integer not null default 30,
  questionspergame integer not null default 5,
  backgroundcolor text not null default 'light',
  fontfamily text not null default 'Inter',
  updatedat timestamptz not null default now()
);

create table public.mejoras (
  id bigint generated by default as identity primary key,
  texto text not null,
  nombre text,
  telefono text,
  userip text,
  useragent text,
  created_at timestamptz not null default now(),
  constraint mejoras_texto_len check (char_length(trim(texto)) between 1 and 2000)
);

create table public.player_aliases (
  ip text,
  alias text,
  createdat timestamptz not null default now(),
  playerid text primary key,
  grupo text not null references public.player_aliases(playerid) on update cascade,
  alias_anterior text
);
create index player_aliases_ip_idx on public.player_aliases (ip);
create index player_aliases_grupo_idx on public.player_aliases (grupo);
create unique index player_aliases_alias_unique_idx
  on public.player_aliases (lower(btrim(alias))) where alias is not null;

