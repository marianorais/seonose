create or replace function public.reclamar_partida(p_sessionid bigint, p_playerid text)
returns jsonb language plpgsql security definer set search_path to 'public'
as $function$
declare
  v_filas int;
begin
  if p_playerid is null or btrim(p_playerid) = '' or p_sessionid is null then
    return jsonb_build_object('estado', 'sin-datos');
  end if;

  update game_sessions set playerid = p_playerid where id = p_sessionid and playerid is null;
  get diagnostics v_filas = row_count;

  if v_filas = 0 then
    return jsonb_build_object('estado', 'no-aplica');
  end if;

  return jsonb_build_object('estado', 'ok');
end $function$;

create or replace function public.vincular_identidad_por_ip(p_playerid text, p_ip text)
returns jsonb language plpgsql security definer set search_path to 'public'
as $function$
declare
  v_grupo text;
  v_alias text;
begin
  if p_playerid is null or btrim(p_playerid) = '' or p_ip is null or btrim(p_ip) = '' then
    return jsonb_build_object('estado', 'sin-datos');
  end if;

  if exists (select 1 from player_aliases where playerid = p_playerid) then
    return jsonb_build_object('estado', 'ya-tiene');
  end if;

  select a.grupo into v_grupo from player_aliases a where a.ip = p_ip and a.playerid like 'ip:%' limit 1;

  if v_grupo is null then
    return jsonb_build_object('estado', 'sin-coincidencia');
  end if;

  select alias into v_alias from player_aliases where playerid = v_grupo;

  if v_alias is null then
    return jsonb_build_object('estado', 'sin-coincidencia');
  end if;

  insert into player_aliases (playerid, alias, ip, grupo) values (p_playerid, null, p_ip, v_grupo)
  on conflict (playerid) do nothing;

  return jsonb_build_object('estado', 'ok', 'alias', v_alias);
end $function$;
